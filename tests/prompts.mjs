import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import vm from 'node:vm';
import ts from 'typescript';

const source=await fs.readFile(new URL('../src/backend.ts',import.meta.url),'utf8');
const context=vm.createContext({});
vm.runInContext(ts.transpileModule(source.slice(0,source.indexOf('spindle.registerMacro(')),{compilerOptions:{target:ts.ScriptTarget.ES2022}}).outputText,context);
const run=code=>vm.runInContext(code,context);
run(`let config=cloneDefaultConfig('hybrid');
config.bindings['character:alice']={kind:'character',targetId:'alice',speakerUid:'prism-speaker-alice',name:'Alice',aliases:[],color:'#112233',channels:safeChannels(null,'#112233'),source:'manual',pinned:true};`);
const original=run('registryInstruction(config)');
const editor=run('promptEditorState(config)');
assert.equal(editor.active,original);
assert.ok(editor.template.includes('Wrap each complete spoken segment'));
assert.ok(editor.template.includes('{{prismRegistry}}'));
assert.ok(editor.template.includes('{{prismRevision}}'));
assert.ok(editor.template.includes('{{prismThoughts}}'));
assert.ok(editor.template.includes('{{prismProvisional}}'));
assert.ok(editor.template.includes('{{prismPalette}}'));
assert.equal(editor.template.includes('Alice'),false);
assert.ok(editor.template.length<6000);
run(`config.promptTemplate=promptEditorState(config).template.replace('Preserve all wording','Keep all wording');
config.bindings['character:alice'].name='Beatrice';
config.bindings['character:alice'].color='#445566';
config.bindings['character:alice'].channels=safeChannels(null,'#445566');
config.promptThoughtColors=true;`);
const edited=run('promptEditorState(config)');
assert.ok(edited.active.includes('Keep all wording'));
assert.ok(edited.active.includes('Beatrice'));
assert.ok(edited.active.includes('#445566'));
assert.equal(edited.active.includes('Alice'),false);
assert.equal(edited.active.includes('{{prism'),false);
assert.ok(edited.active.includes('For direct internal thought only'));
assert.ok(edited.active.includes(run('compileRegistry(config).revision')));
assert.equal(run('promptEditorState(config,compileRegistry(config),false).active'),'');
run('config.engine="dom"');
assert.equal(run('promptEditorState(config).active'),'');
assert.ok(run('promptEditorState(config).template').length>0);
run('config.engine="hybrid";config.promptTemplate="Use concise dialogue."');
assert.ok(run('registryInstruction(config)').includes('Prism confirmed registry JSON:'));
run('config.promptTemplate="";config.promptThoughtColors=false');
assert.ok(run('promptEditorState(config).active').includes('Do not color internal thoughts.'));
assert.equal(run('promptEditorState(config).template').includes('Use concise dialogue.'),false);
run('config.promptDelivery="macro"');
assert.equal(run('promptEditorState(config).active'),run('registryInstruction(config)'));
run('config=cloneDefaultConfig("llm")');
assert.ok(run('promptEditorState(config).active').includes('No speakers are confirmed'));
assert.equal(run('promptEditorState(config).template').includes('[Prism Hybrid Discovery]'),false);
console.log('Passed populated prompt editor, live registry/revision/thought placeholders, inactive engines, custom/reset behavior, and macro preview.');
